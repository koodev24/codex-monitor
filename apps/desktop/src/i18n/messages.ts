const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  en,
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  ja,
};

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

export function resolveLocale(
  preference: string | null | undefined,
  systemLanguage = typeof navigator === "undefined" ? "en" : navigator.language,
): Locale {
  if (isLocale(preference)) return preference;
  const normalized = systemLanguage.replace("_", "-");
  if (/^zh-(tw|hk|mo|hant)/i.test(normalized)) return "zh-TW";
  if (/^zh/i.test(normalized)) return "zh-CN";
  if (/^ja/i.test(normalized)) return "ja";
  return "en";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template = dictionaries[locale]?.[key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export const defaultTranslate = (key: MessageKey): string => en[key];

/**
 * Translate for non-React code (Redux thunks, helpers). Callers pass the
 * stored preference so a status message matches the visible interface.
 */
export function translateFor(
  preference: string | null | undefined,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  return translate(resolveLocale(preference), key, params);
}
